import assert from 'node:assert/strict';
import {readFile,writeFile,readdir,mkdir,copyFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

// public/ remains the canonical source for the backend and original PNG downloads.
// Committed browser copies let AI Studio bundle images without its public-file router.
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const check=process.argv.includes('--check');
const entries=[];
for(const folder of ['viet-y-v2','outfit-photo-v1']){
 const source=path.join(root,'public/assets',folder);
 const destination=path.join(root,'src/assets/runtime',folder);
 if(!check)await mkdir(destination,{recursive:true});
 for(const name of (await readdir(source)).filter(n=>n.endsWith('.webp')).sort()){
  const original=path.join(source,name),copy=path.join(destination,name);
  if(check)assert.deepEqual(await readFile(copy),await readFile(original),`Run npm run assets:sync: ${folder}/${name}`);
  else await copyFile(original,copy);
  entries.push(` '${'/assets/'+folder+'/'+name}':new URL('./runtime/${folder}/${name}',import.meta.url).href,`);
 }
}
const registry=`// Generated by npm run assets:sync. Keep the catalog's server URLs unchanged.\nconst browserAssets:Record<string,string>={\n${entries.join('\n')}\n};\nexport function browserAsset(path:string):string{return browserAssets[path]??path;}\n`;
const registryPath=path.join(root,'src/assets/browserAssets.ts');
if(check)assert.equal(await readFile(registryPath,'utf8'),registry,'Run npm run assets:sync');
else await writeFile(registryPath,registry);
console.log(`PASS: ${entries.length} bundled browser images match the canonical assets`);
